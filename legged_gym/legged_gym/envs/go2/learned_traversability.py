"""Adapters for learned traversability risk maps."""

from pathlib import Path

import numpy as np
from PIL import Image


class PredCostTraversabilityProvider:
    """Replay exported traversability cost images as local BEV risk maps.

    This is an integration adapter for the fourth-chapter main pipeline. It
    consumes ``pred_cost/*.png`` generated by ``infer_rugd_traversability.py``
    and reshapes the learned risk into the existing FMM/U-MPPI traversability
    cost interface. The geometric camera-to-BEV projection can later replace
    this adapter without changing planner-side cost code.
    """

    def __init__(
        self,
        cost_dir,
        bev_shape,
        update_interval=4,
        flip_vertical=True,
        flip_horizontal=True,
        obstacle_cost=1.0,
    ):
        self.cost_dir = Path(cost_dir).expanduser()
        if self.cost_dir.name != "pred_cost" and (self.cost_dir / "pred_cost").is_dir():
            self.cost_dir = self.cost_dir / "pred_cost"
        self.files = sorted(self.cost_dir.glob("*.png"))
        if not self.files:
            raise FileNotFoundError("no pred_cost PNG files found in %s" % self.cost_dir)
        self.bev_shape = tuple(int(v) for v in bev_shape)
        if len(self.bev_shape) != 2:
            raise ValueError("bev_shape must be (H, W)")
        self.update_interval = max(1, int(update_interval))
        self.flip_vertical = bool(flip_vertical)
        self.flip_horizontal = bool(flip_horizontal)
        self.obstacle_cost = float(np.clip(obstacle_cost, 0.0, 1.0))
        self._offset = 0
        self._last_index = None
        self._last_cost = None

    def reset(self, trial_id=0):
        self._offset = int(trial_id) * 17
        self._last_index = None
        self._last_cost = None

    def _load_index(self, index):
        path = self.files[index % len(self.files)]
        image = Image.open(path).convert("L")
        # PIL expects (width, height), while BEV shape is (height, width).
        image = image.resize((self.bev_shape[1], self.bev_shape[0]), Image.BILINEAR)
        cost = np.asarray(image, dtype=np.float32) / 255.0
        if self.flip_vertical:
            cost = np.flipud(cost)
        if self.flip_horizontal:
            cost = np.fliplr(cost)
        return np.ascontiguousarray(np.clip(cost, 0.0, 1.0), dtype=np.float32)

    def get_cost(self, step, occ_bev=None):
        index = (int(step) // self.update_interval + self._offset) % len(self.files)
        if self._last_cost is None or index != self._last_index:
            self._last_cost = self._load_index(index)
            self._last_index = index
        cost = self._last_cost.copy()
        if occ_bev is not None and self.obstacle_cost > 0.0:
            occ = np.asarray(occ_bev, dtype=bool)
            if occ.shape != cost.shape:
                raise ValueError("occ_bev shape %s does not match learned cost %s"
                                 % (occ.shape, cost.shape))
            cost[occ] = self.obstacle_cost
        return np.clip(cost, 0.0, 1.0).astype(np.float32)
